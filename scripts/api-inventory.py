#!/usr/bin/env python3
"""Inventory the CheckDom dashboard's API calls, to notice when the unofficial API changes.

Downloads the public dashboard scripts listed in scripts/dashboard-scripts.txt (static files,
no login) and writes docs/api-inventory.txt:

  * every (controller, action) pair the scripts call, and
  * a SHA-256 of each script that calls an action this server uses (src/tools.rs), so a
    changed parameter list in one of those scripts is noticed too.

Usage:
  scripts/api-inventory.py            rewrite docs/api-inventory.txt
  scripts/api-inventory.py --check    print a diff against it; exit 1 if anything changed,
                                      2 if the scripts could not be downloaded

Standard library only. See .claude/skills/checkdom-api-drift/SKILL.md for what to do with a diff.
"""

import difflib
import hashlib
import pathlib
import re
import sys
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "scripts" / "dashboard-scripts.txt"
INVENTORY = ROOT / "docs" / "api-inventory.txt"
TOOLS = ROOT / "src" / "tools.rs"
BASE = "https://checkdom.in.ua"
USER_AGENT = "checkdom-mcp-api-inventory (+https://github.com/damienmiheev/checkdom-mcp)"

# A controller URL: a literal "/modules/x/api/y.php", or "<modulePathApi> + 'y.php'".
URL = re.compile(
    r"""['"`](/(?:modules/\w+|core)/api/\w+\.php)['"`]"""
    r"""|(?:self|this)\.modulePathApi\s*\+\s*['"`](\w+\.php)['"`]"""
)
BASE_PATH = re.compile(r"""modulePathApi\s*=\s*['"`](/modules/\w+/api/)['"`]""")
# Positional ajaxCall('action', ...), and object forms { action: 'x' } / { request: 'x' }.
CALL = re.compile(r"""ajaxCall\(\s*['"`](\w+)['"`]""")
KEYED = re.compile(r"""\b(?:action|request)\s*:\s*['"`](\w+)['"`]""")


def script_paths():
    lines = SCRIPTS.read_text(encoding="utf-8").splitlines()
    return [l.strip() for l in lines if l.strip() and not l.lstrip().startswith("#")]


def fetch(path):
    req = urllib.request.Request(BASE + path, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return resp.read().decode("utf-8", errors="replace")
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise


def calls_in(text):
    """(controller, action) pairs: each call is matched to the nearest controller URL."""
    base = BASE_PATH.search(text)
    base = base.group(1) if base else None

    def urls(chunk):
        out = []
        for m in URL.finditer(chunk):
            if m.group(1):
                out.append(m.group(1))
            elif base:
                out.append(base + m.group(2))
        return out

    every_url = list(dict.fromkeys(urls(text)))
    pairs = set()
    found = [(m.group(1), text[m.end() : m.end() + 700].split("ajaxCall(")[0]) for m in CALL.finditer(text)]
    found += [(m.group(1), text[max(0, m.start() - 400) : m.end() + 400]) for m in KEYED.finditer(text)]
    for action, chunk in found:
        near = urls(chunk) or (every_url if len(every_url) == 1 else [])
        pairs.add((near[0] if near else "?", action))
    return pairs


def used_actions():
    """Actions this server calls: tool actions plus direct rpc(...) calls in src/tools.rs."""
    src = TOOLS.read_text(encoding="utf-8")
    return set(re.findall(r'action: "(\w+)"', src)) | set(re.findall(r'\.rpc\(\s*\w+,\s*"(\w+)"', src))


def build():
    used = used_actions()
    pairs, hashes, missing = set(), [], []
    for path in script_paths():
        text = fetch(path)
        if text is None:
            missing.append(path)
            continue
        found = calls_in(text)
        pairs |= found
        if any(action in used for _, action in found):
            hashes.append((path, hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]))
    out = ["# Generated by scripts/api-inventory.py; do not edit. Diffs mean the dashboard changed.", ""]
    out.append("## Actions (controller action; * = used by this server)")
    for controller, action in sorted(pairs):
        mark = "*" if action in used else " "
        out.append(f"{mark} {controller.replace('/modules/', '')} {action}")
    out += ["", "## Scripts with actions this server uses (sha256, first 16 hex)"]
    out += [f"{digest} {path}" for path, digest in sorted(hashes)]
    out += ["", "## Listed scripts that no longer exist"]
    out += missing or ["(none)"]
    unseen = sorted(used - {a for _, a in pairs})
    out += ["", "## Actions this server uses that no script calls any more"]
    out += unseen or ["(none)"]
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    try:
        new = build()
    except (urllib.error.URLError, OSError) as e:
        # Exit 2, not 1: a network problem is not a change in the API.
        print(f"could not download the dashboard scripts: {e}", file=sys.stderr)
        return 2
    if not check:
        INVENTORY.write_text(new, encoding="utf-8")
        print(f"wrote {INVENTORY.relative_to(ROOT)}")
        return 0
    old = INVENTORY.read_text(encoding="utf-8") if INVENTORY.exists() else ""
    if old == new:
        print("No change in the dashboard's API inventory.")
        return 0
    sys.stdout.writelines(
        difflib.unified_diff(old.splitlines(True), new.splitlines(True), "committed", "current")
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
